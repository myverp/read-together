test("notes filter authors, retain failed edits, export only mine and reopen a quote without moving partner", async ({ page, request }, testInfo) => {
  const room = await openReader(page);
  const endpoint = `/api/rooms/${room.code}/highlights`;
  const errors: string[] = []; page.on("pageerror", error => errors.push(error.message));
  const dialog = page.getByRole("dialog", { name: "Notes", exact: true });
  await selectReaderAction(page, "Notes");
  await expect(dialog.getByText(/No notes yet/)).toBeVisible();
  await expect(dialog.getByRole("button", { name: "Export my notes" })).toBeDisabled();
  await page.keyboard.press("Escape");
  await expect(page.getByRole("button", { name: "Reader menu", exact: true })).toBeFocused();
  await page.frameLocator(".book-view iframe").locator("p").first().evaluate(element => {
    const range = element.ownerDocument.createRange(); range.setStart(element.firstChild!, 0); range.setEnd(element.firstChild!, 12);
    const selection = element.ownerDocument.getSelection()!; selection.removeAllRanges(); selection.addRange(range);
  });
  await page.getByRole("button", { name: "Highlight selection", exact: true }).click();
  await page.getByLabel("Comment (optional)").fill("My original comment");
  await page.getByRole("button", { name: "Save highlight" }).click();
  await expect(page.getByRole("dialog")).toHaveCount(0);
  const first = (await (await request.get(endpoint, { headers: room.headers })).json()).items[0];
  const second = { id: randomUUID(), cfi: first.cfi.replace("/6/2!", "/6/4!"), quote: "Second chapter quote", comment: "My second note" };
  expect((await request.post(endpoint, { headers: room.headers, data: second })).status()).toBe(200);
  const partnerHeaders = { Authorization: `Bearer ${randomBytes(32).toString("hex")}` };
  expect((await request.post(`/api/rooms/${room.code}`, { headers: partnerHeaders })).status()).toBe(200);
  expect((await request.post(endpoint, { headers: partnerHeaders, data: { ...second, id: randomUUID(), quote: "Partner-only quote", comment: "Partner secret note" } })).status()).toBe(200);
  const partnerBefore = await (await request.get(`/api/rooms/${room.code}/state`, { headers: partnerHeaders })).json();
  await page.getByRole("button", { name: "Done here", exact: true }).click();
  const before = await room.position();
  await selectReaderAction(page, "Notes");
  await expect(dialog.getByRole("article")).toHaveCount(3);
  await expect(dialog.getByRole("article").filter({ hasText: "Partner-only quote" }).getByRole("button", { name: "Edit comment" })).toHaveCount(0);
  await dialog.getByLabel("Author", { exact: true }).selectOption("mine");
  await expect(dialog.getByRole("article")).toHaveCount(2);
  await dialog.getByLabel("Search notes").fill("SECOND NOTE");
  await expect(dialog.getByRole("article")).toHaveCount(1);
  await dialog.getByLabel("Search notes").fill("missing match");
  await expect(dialog.getByText(/No notes match/)).toBeVisible();
  await dialog.getByLabel("Search notes").fill("");
  const own = dialog.getByRole("article").filter({ hasText: first.quote });
  await own.getByRole("button", { name: "Edit comment" }).click();
  await dialog.getByLabel("Comment", { exact: true }).fill("Updated <img src=x> & thought");
  await page.keyboard.press("Escape");
  await expect(dialog.getByText(/Discard your unsaved/)).toBeVisible();
  await dialog.getByRole("button", { name: "Keep editing" }).click();
  await expect(dialog.getByLabel("Comment", { exact: true })).toBeFocused();
  await page.route(`**${endpoint}`, route => route.request().method() === "PATCH" ? route.fulfill({ status: 503, json: { error: "Temporary notes outage" } }) : route.continue());
  await dialog.getByRole("button", { name: "Save comment" }).click();
  await expect(dialog.getByRole("alert")).toContainText("Temporary notes outage");
  await expect(dialog.getByLabel("Comment", { exact: true })).toHaveValue("Updated <img src=x> & thought");
  await page.unroute(`**${endpoint}`);
  await dialog.getByRole("button", { name: "Save comment" }).click();
  await expect(dialog.getByText("Comment saved.", { exact: true })).toBeVisible();
  await expect(own).toContainText("Updated <img src=x> & thought"); await expect(dialog.locator("img")).toHaveCount(0);
  expect(await room.position()).toEqual(before);
  await dialog.getByLabel("Author", { exact: true }).selectOption("partner");
  const downloadEvent = page.waitForEvent("download"); await dialog.getByRole("button", { name: "Export my notes" }).click();
  const download = await downloadEvent; expect(download.suggestedFilename()).toBe("read-together-notes.md");
  const markdown = await readFile((await download.path())!, "utf8");
  expect(markdown).toContain("My second note"); expect(markdown).toContain("Updated &lt;img src=x\\> &amp; thought");
  expect(markdown).not.toContain("Partner-only"); expect(markdown).not.toContain("Partner secret");
  await dialog.getByRole("button", { name: "Close notes" }).click();
  for (const [theme, background] of [["Dark", "rgb(23, 25, 30)"], ["Sepia", "rgb(244, 236, 216)"]]) {
    await applyReadingSettings(page, 18, theme); await selectReaderAction(page, "Notes");
    await expect(dialog).toHaveCSS("background-color", background);
    await page.setViewportSize({ width: 320, height: 480 });
    expect(await dialog.evaluate(element => element.scrollWidth <= element.clientWidth)).toBe(true);
    await page.screenshot({ path: testInfo.outputPath(`notes-${theme}.png`) });
    await dialog.getByRole("button", { name: "Close notes" }).click();
  }
  await selectReaderAction(page, "Notes");
  await page.setViewportSize({ width: 1280, height: 800 });
  expect(await dialog.evaluate(element => element.scrollWidth <= element.clientWidth && element.getBoundingClientRect().width <= innerWidth)).toBe(true);
  await dialog.getByRole("article").first().scrollIntoViewIfNeeded();
  await page.screenshot({ path: testInfo.outputPath("notes-desktop.png") });
  await dialog.getByRole("article").filter({ hasText: "Second chapter quote" }).getByRole("button", { name: "Go to quote" }).click();
  await expect(dialog).toHaveCount(0);
  await expect.poll(async () => (await room.position()).cfi).toContain("/6/4!");
  const destination = await room.position(); expect(destination.done).toBe(false);
  await room.reopen(); expect((await room.position()).cfi).toBe(destination.cfi);
  const partnerAfter = await (await request.get(`/api/rooms/${room.code}/state`, { headers: partnerHeaders })).json();
  expect(partnerAfter.me).toEqual(partnerBefore.me);
  await selectReaderAction(page, "Notes");
  const removeNote = dialog.getByRole("article").filter({ hasText: "Second chapter quote" });
  await removeNote.getByRole("button", { name: "Remove", exact: true }).click();
  await removeNote.getByRole("button", { name: "Cancel removal" }).click();
  await removeNote.getByRole("button", { name: "Remove", exact: true }).click();
  await removeNote.getByRole("button", { name: "Remove highlight" }).click();
  await expect(removeNote).toHaveCount(0); expect(errors).toEqual([]);
});

test("notes keep drafts across conflict and remote removal and expose recoverable loading failures", async ({ page, request }) => {
  const room = await openReader(page), endpoint = `/api/rooms/${room.code}/highlights`;
  const mark = { id: randomUUID(), cfi: 'epubcfi(/6/2!/4/4,/1:0,/1:12)', quote: "Conflict quote", comment: "Original" };
  expect((await request.post(endpoint, { headers: room.headers, data: mark })).status()).toBe(200);
  await selectReaderAction(page, "Notes"); const dialog = page.getByRole("dialog", { name: "Notes", exact: true });
  await dialog.getByRole("button", { name: "Edit comment" }).click();
  await dialog.getByLabel("Comment", { exact: true }).fill("Local draft");
  expect((await request.patch(endpoint, { headers: room.headers, data: { id: mark.id, previousComment: "Original", comment: "Changed elsewhere" } })).status()).toBe(200);
  await dialog.getByRole("button", { name: "Save comment" }).click();
  await expect(dialog.getByText(/This comment changed elsewhere/)).toBeVisible();
  await expect(dialog.getByLabel("Comment", { exact: true })).toHaveValue("Local draft");
  await dialog.getByRole("button", { name: "Cancel editing" }).click();
  await expect(dialog.getByRole("article")).toContainText("Changed elsewhere");
  await dialog.getByRole("button", { name: "Edit comment" }).click();
  await dialog.getByLabel("Comment", { exact: true }).fill("Draft after removal");
  expect((await request.delete(endpoint, { headers: room.headers, data: { id: mark.id } })).status()).toBe(200);
  await dialog.getByRole("button", { name: "Save comment" }).click();
  await expect(dialog.getByLabel("Comment", { exact: true })).toHaveValue("Draft after removal");
  await expect(dialog.getByRole("button", { name: "Save comment" })).toBeDisabled();
  await page.keyboard.press("Escape"); await dialog.getByRole("button", { name: "Discard and close" }).click();
  await page.route(`**${endpoint}`, route => route.fulfill({ status: 503, json: { error: "Notes unavailable" } }));
  await page.reload(); await expect(page.getByRole("button", { name: "Done here", exact: true })).toBeEnabled();
  await selectReaderAction(page, "Notes"); await expect(dialog.getByText("Notes could not load.")).toBeVisible();
  await expect(dialog.getByRole("button", { name: "Export my notes" })).toBeDisabled();
  await page.unroute(`**${endpoint}`); await dialog.getByRole("button", { name: "Retry notes" }).click();
  await expect(dialog.getByText(/No notes yet/)).toBeVisible();
});
